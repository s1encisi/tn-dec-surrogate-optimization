"""Synthetic prediction, model interpretation and support-constrained Pareto comparison.

The demonstration is fully self-contained: every input record is generated by
:func:`synthetic_data` from deliberately invented formulas, so no private factory
record, frozen model or manuscript number is ever read.
"""

